import {build} from 'esbuild';
import {cpSync,copyFileSync,mkdirSync,mkdtempSync,readFileSync,writeFileSync,existsSync,unlinkSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {spawnSync} from 'node:child_process';
import {createRequire} from 'node:module';
import path from 'node:path';

const root=path.resolve('.');
const digest=file=>createHash('sha256').update(readFileSync(file)).digest('hex');
const original=JSON.parse(readFileSync('evidence/document-command-task1/ORIGINAL.json','utf8').replace(/^\uFEFF/,''));
if(digest(original.snapshot)!==original.sha256)throw Error('Original snapshot hash mismatch');
const liveFiles=['src/renderer/reading-commands.ts','src/shared/document-commands.ts','tests/document-commands.test.ts'];
const liveHashes=liveFiles.map(file=>digest(file));
const base=path.join(root,'.cache/document-command-task1-rollback');mkdirSync(base,{recursive:true});
const copy=mkdtempSync(path.join(base,'run-'));
const inside=file=>{const resolved=path.resolve(copy,file);if(!resolved.startsWith(copy+path.sep))throw Error('Invalid isolated path');return resolved;};
cpSync('src',inside('src'),{recursive:true});
mkdirSync(inside('tests'),{recursive:true});
copyFileSync('tests/reading-commands.test.ts',inside('tests/reading-commands.test.ts'));
copyFileSync('vitest.config.mts',inside('vitest.config.mts'));
writeFileSync(inside('package.json'),JSON.stringify({type:'module'}));
copyFileSync(original.snapshot,inside(original.target));
if(digest(inside(original.target))!==original.sha256)throw Error('Restored hash mismatch');
const added=inside('src/shared/document-commands.ts');if(existsSync(added))unlinkSync(added);
await build({entryPoints:[inside(original.target)],outfile:inside('baseline.cjs'),bundle:true,platform:'node',format:'cjs'});
const api=createRequire(import.meta.url)(inside('baseline.cjs'));
if(typeof api.executeReadingCommand!=='function'||'runDocumentCommand' in api)throw Error('Baseline API not restored');
const calls=[];api.executeReadingCommand({type:'pause_session'},{showEvidence:()=>calls.push('focus'),clearFocus:()=>calls.push('clear'),pause:()=>calls.push('pause')});
if(JSON.stringify(calls)!=='["pause"]')throw Error('Baseline pause failed');
const test=spawnSync(process.execPath,[path.join(root,'node_modules/vitest/vitest.mjs'),'run','--root',copy,'tests/reading-commands.test.ts'],{cwd:root,encoding:'utf8',windowsHide:true});
process.stdout.write(test.stdout||'');process.stderr.write(test.stderr||'');
if(test.error||test.status!==0)throw Error('Isolated baseline tests failed: '+test.status);
if(liveFiles.some((file,i)=>digest(file)!==liveHashes[i]))throw Error('Live modified files changed');
console.log('ROLLBACK: ORIGINAL_HASH=PASS; LEGACY_API=PASS; EXECUTOR_ABSENT=YES; LEGACY_TESTS=PASS; LIVE_MODIFIED_FILES_UNCHANGED=YES');
