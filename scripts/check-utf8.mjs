import { execFileSync, spawnSync } from 'node:child_process';
import { mkdirSync } from 'node:fs';
import path from 'node:path';
const python = path.resolve('.venv/Scripts/python.exe');
const folder = path.resolve('.cache/utf8-check'); mkdirSync(folder, { recursive: true });
const source = path.join(folder, '中文.pdf');
execFileSync(python, ['-c', `import pymupdf as f;d=f.open();d.new_page();d.save(${JSON.stringify(source)});d.close()`]);
const request = JSON.stringify({ operation: 'inspect', source });
const result = spawnSync(python, [path.resolve(process.argv[2] || 'python/export_pdf.py')], { input: request, encoding: 'utf8', env: { ...process.env, PYTHONIOENCODING: 'gbk', PYTHONUTF8: '0' }, windowsHide: true });
const success = result.status === 0 && JSON.parse(result.stdout).value?.pageCount === 1;
console.log(`UTF8_INSPECT: ${success ? 'PASS' : 'FAIL'}`);
process.exitCode = success ? 0 : 1;
